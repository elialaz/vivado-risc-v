"""Generate a 64-bit GRLIB AHB ROM (VHDL) from a raw boot image.

The ROM decodes only its low address bits, so it can be mapped at a second
(alias) window as well. Same AHB behaviour as GRLIB's bin/ahbrom.c 64-bit ROM (zero wait states,
little-endian word packing), but the image is held in a constant array read
synchronously with the AHB address-phase address, so Vivado infers block RAM
instead of a large LUT case statement.

usage: gen-ahbrom.py <image.bin> <out.vhd> [entity-name]
"""
import sys


def main():
    if len(sys.argv) not in (3, 4):
        sys.exit(__doc__)
    image = open(sys.argv[1], "rb").read()
    entity = sys.argv[3] if len(sys.argv) == 4 else "NOELVBootRom"

    words = (len(image) + 7) // 8
    abits = 3
    while (1 << abits) < max(words * 8, 64):
        abits += 1
    depth = 1 << (abits - 3)
    image = image.ljust(depth * 8, b"\0")

    lines = []
    for i in range(depth):
        w = int.from_bytes(image[i * 8:(i + 1) * 8], "little")
        sep = "," if i + 1 < depth else ""
        lines.append(f'    {i} => x"{w:016x}"{sep}')
    rom = "\n".join(lines)

    vhdl = f"""-- Generated by scripts/native/gen-ahbrom.py from {sys.argv[1].split('/')[-1]}
-- {len(image)} bytes, {depth} 64-bit words. Do not edit.
library ieee;
use ieee.std_logic_1164.all;
use ieee.numeric_std.all;
library grlib;
use grlib.amba.all;
use grlib.stdlib.all;
use grlib.devices.all;
use grlib.config_types.all;
use grlib.config.all;

entity {entity} is
  generic (
    hindex : integer := 0;
    haddr  : integer := 0;
    hmask  : integer := 16#fff#;
    -- optional second (alias) window; hmask2 = 0 disables it
    haddr2 : integer := 0;
    hmask2 : integer := 0);
  port (
    rst    : in  std_ulogic;
    clk    : in  std_ulogic;
    ahbsi  : in  ahb_slv_in_type;
    ahbso  : out ahb_slv_out_type);
end;

architecture rtl of {entity} is
  constant abits : integer := {abits};
  type rom_type is array (0 to {depth - 1}) of std_logic_vector(63 downto 0);
  constant rom : rom_type := (
{rom});

  constant hconfig : ahb_config_type := (
    0 => ahb_device_reg(VENDOR_GAISLER, GAISLER_AHBROM, 0, 0, 0),
    4 => ahb_membar(haddr, '1', '1', hmask),
    5 => ahb_membar(haddr2, '1', '1', hmask2), others => zero32);

  signal romdata : std_logic_vector(63 downto 0);
  signal addr    : std_logic_vector(4 downto 2);
  signal hsize   : std_logic_vector(2 downto 0);
begin
  ahbso.hresp   <= "00";
  ahbso.hsplit  <= (others => '0');
  ahbso.hirq    <= (others => '0');
  ahbso.hconfig <= hconfig;
  ahbso.hindex  <= hindex;
  ahbso.hready  <= '1';

  reg : process (clk)
  begin
    if rising_edge(clk) then
      romdata <= rom(to_integer(unsigned(ahbsi.haddr(abits-1 downto 3))));
      addr    <= ahbsi.haddr(4 downto 2);
      hsize   <= ahbsi.hsize;
    end if;
  end process;

  ahbso.hrdata <= ahbselectdata(ahbdrivedata(romdata), addr, hsize);
end;
"""
    open(sys.argv[2], "w").write(vhdl)
    print(f"{sys.argv[2]}: {len(image)} bytes, {depth} words, {abits} address bits")


if __name__ == "__main__":
    main()
